WEIGHT = {'ukraine': 0.5, 'talk': 0.5}

_cache = {}


def _re(cid, words):
    key = (cid, words)
    if key not in _cache:
        _cache[key] = re.compile(r'(?<!\w)(?:%s)' % words, re.I) if words else None
    return _cache[key]


def defaults():
    return [{'id': c[0], 'name': c[1], 'words': c[2]} for c in DEFAULT]


def categories():
    """Список категорий пользователя (или стандартные)."""
    c = cfg.S.get('cats')
    if not c:
        c = defaults()
        cfg.S['cats'] = c
        cfg.S['cats_v2'] = 1
        cfg.save()
    elif not cfg.S.get('cats_v2'):                 # у тех, кто уже пользовался: новые темы для игры добавляем в начало списка один раз
        ids = {x['id'] for x in c}
        names = {(x.get('name') or '').strip().lower() for x in c}
        add = [d for d in defaults() if d['id'] in HOT and d['id'] not in ids and d['name'].lower() not in names]
        c[0:0] = add
        cfg.S['cats_v2'] = 1
        cfg.save()
    return c


def view():
    """Категории для окна: с пометкой «для игры» (hot)."""
    return [dict(c, hot=c['id'] in HOT) for c in categories()]


def guess(title, username=''):
    """Возвращает id категории по названию чата."""
    t = ('%s %s' % (title or '', username or '')).lower()
    best, score = OTHER, 0
    for c in categories():
        rx = _re(c['id'], c.get('words', ''))
        if not rx:
            continue
        n = len(rx.findall(t)) * WEIGHT.get(c['id'], 1.0)
        if n > score:
            best, score = c['id'], n
    if not any(c['id'] == best for c in categories()):
        best = OTHER
    return best


def queries(cid):
    """Слова для поиска по теме. У своей категории — её название."""
    q = SEARCH.get(cid)
    if q is not None:
        return list(q)
    for c in categories():
        if c['id'] == cid:
            name = (c.get('name') or '').strip()
            return [name] if name else []
    return []


def valid_id(cid):
    return any(c['id'] == cid for c in categories())


def add(name):
    name = (name or '').strip()[:40]
    if not name:
        raise ValueError('Введи название категории')
    cs = categories()
    if any(c['name'].lower() == name.lower() for c in cs):
        raise ValueError('Такая категория уже есть')
    cid = 'c%d' % cfg.now()
    cs.insert(max(0, len(cs) - 1), {'id': cid, 'name': name, 'words': ''})
    cfg.save()
    return cid


def rename(cid, name):
    name = (name or '').strip()[:40]
    if not name:
        raise ValueError('Введи название категории')
    for c in categories():
        if c['id'] == cid:
            c['name'] = name
            cfg.save()
            return
    raise ValueError('Нет такой категории')


def delete(cid):
    if cid == OTHER:
        raise ValueError('Категорию «Другое» удалить нельзя')
    cs = categories()
    cs[:] = [c for c in cs if c['id'] != cid]
    for ch in cfg.S['chats'].values():
        if ch.get('cat') == cid:
            ch['cat'] = OTHER
            ch['manual'] = False
    cfg.save()
